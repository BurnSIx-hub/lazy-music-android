package com.lazymusic.app

import okhttp3.Dns
import java.net.Inet4Address
import java.net.InetAddress

/**
 * Адреса сервера в порядке «сначала IPv4».
 *
 * Система отдаёт их наоборот — сначала IPv6, — и обычно это правильно.
 * Здесь это ломало музыку на мобильной сети, и вот как это выяснилось
 * (замер 2026-10-07, Galaxy S23, Telefónica):
 *
 * ```
 * узел 87d, адреса по порядку 64, IPv6 — не вышло за 4005 мс, IPv4 — 18 мс
 * ```
 *
 * До серверов со звуком по IPv6 не дозвониться вовсе, хотя сам youtube.com
 * по IPv6 открывается. Штатный сетевой слой Android не умеет пробовать
 * оба семейства разом: он ждал IPv6 все восемь секунд таймаута и только
 * потом шёл на IPv4. Каждый первый трек на мобильной сети начинался
 * с восьми секунд тишины.
 *
 * Хуже того, ссылка на звук привязана к адресу, с которого её добыли.
 * yt-dlp ходил на YouTube по IPv6 и получал ссылку под IPv6-адрес, а плеер
 * в итоге приходил за звуком с IPv4 — и YouTube то пускал, то отвечал 403.
 *
 * Поэтому обе стороны теперь ходят по IPv4: плеер — через этот порядок
 * адресов, yt-dlp — через [Engine.IPV4]. Менять надо **обе** разом:
 * одна без другой даёт ровно тот разнобой, от которого уходили.
 *
 * IPv6 при этом не запрещён, а отодвинут: в сети, где IPv4 нет совсем,
 * список будет состоять из одних IPv6-адресов, и всё пойдёт по ним.
 */
object Ipv4First : Dns {

    override fun lookup(hostname: String): List<InetAddress> =
        // Сортировка устойчивая: внутри семейства порядок системы сохраняется
        Dns.SYSTEM.lookup(hostname).sortedBy { if (it is Inet4Address) 0 else 1 }
}
